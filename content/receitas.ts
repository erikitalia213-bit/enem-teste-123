import { ingredientes } from "./ingredientes";
import type { IngredienteReceita, Receita, Refeicao, Unidade } from "./tipos";

/**
 * Receitas do cardápio sugerido: comida brasileira, acessível e rica em proteína.
 * A proteína é APROXIMADA, por porção, e serve só como referência.
 *
 * Para adicionar uma receita: copie um bloco, troque o `id` (único, sem acento) e use
 * ingredientes do catálogo (content/ingredientes.ts). Depois rode `npm run validar:conteudo`.
 */

/** Atalho para declarar ingredientes: i("ovo", 2) ou i("azeite", 1, "colher-sopa", "para untar"). */
function i(item: string, qtd: number | null, unidade?: Unidade, obs?: string): IngredienteReceita {
  const cat = ingredientes[item];
  if (!cat) throw new Error(`Ingrediente fora do catálogo: ${item}`);
  const ing: IngredienteReceita = { item, qtd, unidade: unidade ?? cat.unidade };
  if (obs) ing.obs = obs;
  return ing;
}
const aGosto = (item: string, obs?: string) => i(item, null, "a-gosto", obs);

