const porId = new Map(receitas.map((r) => [r.id, r]));

export function obterReceita(id: string): Receita | undefined {
  return porId.get(id);
}

export function exigirReceita(id: string): Receita {
  const r = porId.get(id);
  if (!r) throw new Error(`Receita não encontrada: ${id}`);
  return r;
}
